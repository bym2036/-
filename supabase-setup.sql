-- 1. 기존 테이블이 있다면 초기화 (처음 실행 시에는 그냥 지나갑니다)
drop table if exists rolling_papers;

-- 2. 롤링페이퍼 메시지 테이블 생성
create table rolling_papers (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  sender text not null,
  content text not null,
  color text default 'yellow',
  emoji text default '🎉'
);

-- 3. 보안(RLS) 활성화
alter table rolling_papers enable row level security;

-- 4. 누구나 메시지를 읽을 수 있도록 허용하는 정책 (Public Read)
create policy "누구나 롤링페이퍼를 읽을 수 있습니다" 
on rolling_papers for select 
to anon, authenticated 
using (true);

-- 5. 누구나 메시지를 작성할 수 있도록 허용하는 정책 (Public Insert)
create policy "누구나 롤링페이퍼에 글을 쓸 수 있습니다" 
on rolling_papers for insert 
to anon, authenticated 
with check (true);

-- 6. 첫 시작을 축하하는 샘플 웰컴 메시지 2개 추가!
insert into rolling_papers (sender, content, color, emoji) 
values 
  ('운영자', '🎉 배영민 님의 롤링페이퍼 오픈을 축하합니다! 따뜻한 응원의 한마디를 남겨주세요 💕', 'yellow', '🎉'),
  ('익명의 친구', '영민님 언제나 응원합니다! 앞으로 하시는 모든 일 다 잘 풀리실 거예요 🍀✨', 'pink', '🍀');

